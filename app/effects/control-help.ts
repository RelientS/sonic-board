function bandLesson(id: string): LessonText {
  const frequency = Number(id);
  const area = frequency <= 200 ? '低频与重量' : frequency <= 800 ? '低中频与箱体厚度' : frequency <= 1600 ? '中频与和弦可读性' : '高频轮廓与噪点';
  return {
    summary: `提升或削减 ${id} Hz 附近的${area}。`,
    low: '削减这个频段，为其他乐器腾位置。',
    high: '提升这个频段，让对应特征更明显。',
    tip: '每次只移动少量并反复旁通比较，图示均衡很容易累积过度。',
  };
}

export function getControlHelp(kind: ControlOwnerKind, modelId: string, control: ControlSpec): ControlLesson {
  const fallback: LessonText = {
    summary: `调节“${control.label}”在当前模块中的处理强度。`,
    low: '处理程度较轻。',
    high: '处理程度较强。',
    tip: '从默认位置开始，小幅移动并用旁通反复比较。',
  };
  const base = kind === 'amp'
    ? ampLessons[control.id]
    : kind === 'cab'
      ? cabLessons[control.id]
      : /^\d+$/.test(control.id)
        ? bandLesson(control.id)
        : effectLessons[control.id];
  const lesson = { ...fallback, ...base, ...(overrides[`${modelId}.${control.id}`] ?? {}) };
  return {
    ...lesson,
    range: `${control.min} – ${control.max}${control.unit ? ` ${control.unit}` : ''}`,
  };
}
